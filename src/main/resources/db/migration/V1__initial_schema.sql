CREATE TABLE tbl_stage (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    school_id BIGINT NOT NULL,
    type VARCHAR(255) NOT NULL,
    name VARCHAR(255) NOT NULL,
    student_id BIGINT NOT NULL,
    pass_code VARCHAR(255),
    initial_point BIGINT NOT NULL,
    status VARCHAR(255) NOT NULL,
    participant_count INTEGER NOT NULL,
    is_active_minigame BOOLEAN NOT NULL,
    is_active_shop BOOLEAN NOT NULL,
    created_at TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL
);

CREATE TABLE tbl_stage_maintainer (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    stage_id BIGINT NOT NULL REFERENCES tbl_stage(id),
    student_id BIGINT NOT NULL
);

CREATE TABLE tbl_stage_participant (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    stage_id BIGINT NOT NULL REFERENCES tbl_stage(id),
    student_id BIGINT NOT NULL,
    point BIGINT NOT NULL,
    created_at TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL
);

CREATE TABLE tbl_stage_rule (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    stage_id BIGINT NOT NULL UNIQUE REFERENCES tbl_stage(id),
    max_betting_point BIGINT NOT NULL,
    min_betting_point BIGINT NOT NULL
);

CREATE TABLE tbl_stage_minigame_info (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    stage_id BIGINT NOT NULL UNIQUE REFERENCES tbl_stage(id),
    is_active_coin_toss BOOLEAN NOT NULL,
    is_active_yavarwee BOOLEAN NOT NULL,
    is_active_plinko BOOLEAN NOT NULL
);

CREATE TABLE tbl_stage_shop_info (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    stage_id BIGINT NOT NULL UNIQUE REFERENCES tbl_stage(id),
    is_sell_coin_toss_ticket BOOLEAN NOT NULL,
    is_sell_yavarwee_ticket BOOLEAN NOT NULL,
    is_sell_plinko_ticket BOOLEAN NOT NULL
);

CREATE TABLE tbl_game (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    stage_id BIGINT NOT NULL REFERENCES tbl_stage(id),
    category VARCHAR(255) NOT NULL,
    name VARCHAR(255),
    game_system VARCHAR(255) NOT NULL,
    team_min_capacity INTEGER NOT NULL,
    team_max_capacity INTEGER NOT NULL,
    first_place_team_id BIGINT UNIQUE,
    team_count INTEGER NOT NULL,
    league_count INTEGER,
    is_end BOOLEAN NOT NULL
);

CREATE TABLE tbl_team (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    game_id BIGINT NOT NULL REFERENCES tbl_game(id),
    win_count INTEGER NOT NULL,
    name VARCHAR(255) NOT NULL,
    participant_count INTEGER NOT NULL,
    is_participating BOOLEAN NOT NULL
);

ALTER TABLE tbl_game
    ADD CONSTRAINT fk_tbl_game_first_place_team
    FOREIGN KEY (first_place_team_id) REFERENCES tbl_team(id);

CREATE TABLE tbl_team_participant (
    team_participant_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    team_id BIGINT REFERENCES tbl_team(id),
    student_id BIGINT NOT NULL,
    position_x VARCHAR(255),
    position_y VARCHAR(255)
);

CREATE TABLE tbl_match (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    game_id BIGINT NOT NULL REFERENCES tbl_game(id),
    a_team_id BIGINT REFERENCES tbl_team(id),
    b_team_id BIGINT REFERENCES tbl_team(id),
    round VARCHAR(255),
    turn INTEGER,
    league_turn INTEGER,
    start_date TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL,
    end_date TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL,
    is_end BOOLEAN NOT NULL,
    a_team_betting_point BIGINT NOT NULL,
    b_team_betting_point BIGINT NOT NULL
);

CREATE TABLE tbl_match_result (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    match_id BIGINT NOT NULL UNIQUE REFERENCES tbl_match(id),
    victory_team_id BIGINT NOT NULL REFERENCES tbl_team(id),
    a_team_score INTEGER NOT NULL,
    b_team_score INTEGER NOT NULL,
    team_point_expired_date TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL,
    created_at TIMESTAMP(6) WITHOUT TIME ZONE
);

CREATE TABLE tbl_match_notification (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    match_id BIGINT NOT NULL REFERENCES tbl_match(id),
    student_id BIGINT NOT NULL
);

CREATE TABLE tbl_temp_point (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    stage_participant_id BIGINT REFERENCES tbl_stage_participant(id),
    match_id BIGINT REFERENCES tbl_match(id),
    batch_id BIGINT,
    temp_point BIGINT,
    temp_point_expired_date TIMESTAMP(6) WITHOUT TIME ZONE,
    is_applied BOOLEAN
);

CREATE TABLE tbl_community (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    stage_id BIGINT NOT NULL REFERENCES tbl_stage(id),
    category VARCHAR(255) NOT NULL
);

CREATE TABLE tbl_board (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    community_id BIGINT NOT NULL REFERENCES tbl_community(id),
    student_id BIGINT NOT NULL,
    title VARCHAR(30) NOT NULL,
    content VARCHAR(1000) NOT NULL,
    comment_count INTEGER NOT NULL,
    like_count INTEGER NOT NULL,
    view_count INTEGER NOT NULL,
    is_filtered BOOLEAN NOT NULL,
    created_at TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL,
    image_url VARCHAR(800)
);

CREATE TABLE tbl_board_like (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    board_id BIGINT NOT NULL REFERENCES tbl_board(id),
    student_id BIGINT NOT NULL
);

CREATE TABLE tbl_board_view (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    board_id BIGINT NOT NULL REFERENCES tbl_board(id),
    student_id BIGINT NOT NULL
);

CREATE TABLE tbl_comment (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    board_id BIGINT NOT NULL REFERENCES tbl_board(id),
    student_id BIGINT NOT NULL,
    content VARCHAR(300) NOT NULL,
    is_filtered BOOLEAN NOT NULL,
    created_at TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL,
    like_count INTEGER NOT NULL
);

CREATE TABLE tbl_comment_like (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    comment_id BIGINT NOT NULL REFERENCES tbl_comment(id),
    student_id BIGINT NOT NULL
);

CREATE TABLE tbl_coupon (
    id VARCHAR(255) PRIMARY KEY,
    stage_id BIGINT NOT NULL REFERENCES tbl_stage(id),
    type VARCHAR(255) NOT NULL,
    earn_point BIGINT NOT NULL,
    lost_point BIGINT,
    is_used BOOLEAN NOT NULL
);

CREATE TABLE tbl_coupon_result (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    coupon_id VARCHAR(255) NOT NULL UNIQUE REFERENCES tbl_coupon(id),
    student_id BIGINT NOT NULL,
    is_gain BOOLEAN NOT NULL,
    before_point BIGINT NOT NULL,
    after_point BIGINT NOT NULL,
    create_at TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL
);
